import { readdirSync, readFileSync, writeFileSync } from "node:fs";

export function generateMigrations() {
  const directory = new URL("../migrations/", import.meta.url);
  const migrations = readdirSync(directory)
    .filter((name) => /^\d+.*\.sql$/.test(name))
    .sort()
    .map((name) => ({
      version: Number(name.slice(0, 3)),
      sql: readFileSync(new URL(name, directory), "utf8"),
    }));
  return `// Generated by packages/store/scripts/generate-migrations.mjs. Do not edit.\n// biome-ignore format: generated SQL bundle
export const migrations = ${JSON.stringify(migrations)};\n`;
}
const target = new URL("../src/migrations.generated.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== generateMigrations()) {
    throw new Error(
      "Bundled migrations are stale. Run pnpm --filter @zoltbot/store migrations:generate.",
    );
  }
} else writeFileSync(target, generateMigrations());
