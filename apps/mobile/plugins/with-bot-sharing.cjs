const fs = require("node:fs");
const path = require("node:path");
const { withEntitlementsPlist, withInfoPlist, withXcodeProject } = require("expo/config-plugins");

const targetName = "ZoltShareExtension";
const sourceFolder = "ZoltShareNative";
const quote = (value) => JSON.stringify(value);
const unquote = (value) => String(value ?? "").replace(/^"|"$/g, "");
const xml = (value) =>
  String(value).replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll('"', "&quot;");
const plist = (body) => `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>${body}</dict></plist>\n`;

function addTargetSource(project, name, target, group) {
  const sourcePath = `${sourceFolder}/${name}`;
  let reference = Object.entries(project.pbxFileReferenceSection()).find(
    ([key, value]) => !key.endsWith("_comment") && unquote(value.path) === sourcePath,
  )?.[0];
  if (!reference) reference = project.addFile(sourcePath, group).fileRef;
  const children = project.getPBXGroupByKey(group).children;
  if (!children.some((child) => child.value === reference))
    project.addToPbxGroup({ fileRef: reference, basename: name }, group);
  const phase = project.pbxSourcesBuildPhaseObj(target);
  const buildFiles = project.pbxBuildFileSection();
  const existing = phase.files.find((file) => buildFiles[file.value]?.fileRef === reference);
  if (existing) {
    const uses = Object.entries(project.hash.project.objects.PBXSourcesBuildPhase)
      .filter(([key]) => !key.endsWith("_comment"))
      .flatMap(([, value]) => value.files)
      .filter((file) => file.value === existing.value).length;
    if (uses === 1) return;
    // Repair projects generated by the old plugin as well as creating fresh ones.
    phase.files = phase.files.filter((file) => file.value !== existing.value);
  }
  // A PBXFileReference may be shared by targets; a PBXBuildFile must belong to one phase.
  const file = {
    uuid: project.generateUuid(),
    fileRef: reference,
    basename: name,
    group: "Sources",
    target,
  };
  project.addToPbxBuildFileSection(file);
  project.addToPbxSourcesBuildPhase(file);
}

function configureProject(project, root, config) {
  const bundleId = config.ios.bundleIdentifier;
  const appGroup = `group.${bundleId}`;
  const extensionId = `${bundleId}.ShareExtension`;
  const folder = path.join(root, sourceFolder);
  fs.mkdirSync(folder, { recursive: true });
  for (const name of [
    "ShareStore.swift",
    "ShareViewController.swift",
    "ZoltShare.swift",
    "ZoltShareBridge.m",
  ]) {
    fs.copyFileSync(path.join(__dirname, "../native/share", name), path.join(folder, name));
  }
  fs.writeFileSync(
    path.join(folder, "Extension.entitlements"),
    plist(
      `<key>com.apple.security.application-groups</key><array><string>${xml(appGroup)}</string></array>`,
    ),
  );
  fs.writeFileSync(
    path.join(folder, "Extension-Info.plist"),
    plist(`
    <key>CFBundleDisplayName</key><string>Zoltbot</string>
    <key>CFBundleIdentifier</key><string>$(PRODUCT_BUNDLE_IDENTIFIER)</string>
    <key>CFBundleExecutable</key><string>$(EXECUTABLE_NAME)</string>
    <key>CFBundleName</key><string>$(PRODUCT_NAME)</string>
    <key>CFBundlePackageType</key><string>XPC!</string>
    <key>CFBundleShortVersionString</key><string>$(MARKETING_VERSION)</string>
    <key>CFBundleVersion</key><string>$(CURRENT_PROJECT_VERSION)</string>
    <key>ZoltShareAppGroup</key><string>${xml(appGroup)}</string>
    <key>NSExtension</key><dict>
      <key>NSExtensionPointIdentifier</key><string>com.apple.share-services</string>
      <key>NSExtensionPrincipalClass</key><string>$(PRODUCT_MODULE_NAME).ShareViewController</string>
      <key>NSExtensionAttributes</key><dict>
        <key>IntentsSupported</key><array><string>INSendMessageIntent</string></array>
        <key>NSExtensionActivationRule</key><dict>
          <key>NSExtensionActivationSupportsText</key><true/>
          <key>NSExtensionActivationSupportsWebURLWithMaxCount</key><integer>1</integer>
          <key>NSExtensionActivationSupportsImageWithMaxCount</key><integer>5</integer>
        </dict>
      </dict>
    </dict>`),
  );

  const host = project.getFirstTarget();
  let group = project.pbxGroupByName(sourceFolder);
  if (!group) {
    const added = project.addPbxGroup([], sourceFolder, '""');
    project.addToPbxGroup(added.uuid, project.getFirstProject().firstProject.mainGroup);
    group = { uuid: added.uuid };
  } else {
    group = { uuid: project.findPBXGroupKey({ name: sourceFolder }) };
  }
  let extension = Object.entries(project.pbxNativeTargetSection()).find(
    ([key, value]) => !key.endsWith("_comment") && unquote(value.name) === targetName,
  );
  if (!extension) {
    project.hash.project.objects.PBXTargetDependency ??= {};
    project.hash.project.objects.PBXContainerItemProxy ??= {};
    const target = project.addTarget(targetName, "app_extension", sourceFolder, extensionId);
    extension = [target.uuid, target.pbxNativeTarget];
    project.addBuildPhase([], "PBXSourcesBuildPhase", "Sources", target.uuid);
    project.addBuildPhase([], "PBXFrameworksBuildPhase", "Frameworks", target.uuid);
  }
  for (const name of ["ShareStore.swift", "ZoltShare.swift", "ZoltShareBridge.m"])
    addTargetSource(project, name, host.uuid, group.uuid);
  for (const name of ["ShareStore.swift", "ShareViewController.swift"])
    addTargetSource(project, name, extension[0], group.uuid);
  const configurations = project.pbxXCBuildConfigurationSection();
  const list = project.pbxXCConfigurationList()[extension[1].buildConfigurationList];
  for (const entry of list.buildConfigurations) {
    Object.assign(configurations[entry.value].buildSettings, {
      INFOPLIST_FILE: quote(`${sourceFolder}/Extension-Info.plist`),
      CODE_SIGN_ENTITLEMENTS: quote(`${sourceFolder}/Extension.entitlements`),
      PRODUCT_BUNDLE_IDENTIFIER: quote(extensionId),
      PRODUCT_MODULE_NAME: targetName,
      SWIFT_VERSION: "5.0",
      IPHONEOS_DEPLOYMENT_TARGET: "16.0",
      TARGETED_DEVICE_FAMILY: quote("1"),
      APPLICATION_EXTENSION_API_ONLY: "YES",
      GENERATE_INFOPLIST_FILE: "NO",
      MARKETING_VERSION: quote(config.version ?? "1.0"),
      CURRENT_PROJECT_VERSION: quote(config.ios.buildNumber ?? "1"),
      ...(config.ios.appleTeamId ? { DEVELOPMENT_TEAM: config.ios.appleTeamId } : {}),
    });
  }
  return project;
}

function withBotSharing(config) {
  const bundleId = config.ios?.bundleIdentifier;
  if (!bundleId || !/^[A-Za-z0-9.-]+$/.test(bundleId))
    throw new Error("Bot sharing requires an iOS bundle identifier.");
  const appGroup = `group.${bundleId}`;
  config = withEntitlementsPlist(config, (mod) => {
    const groups = mod.modResults["com.apple.security.application-groups"] ?? [];
    mod.modResults["com.apple.security.application-groups"] = [...new Set([...groups, appGroup])];
    return mod;
  });
  config = withInfoPlist(config, (mod) => {
    mod.modResults.ZoltShareAppGroup = appGroup;
    return mod;
  });
  config.extra ??= {};
  config.extra.eas ??= {};
  config.extra.eas.build ??= {};
  config.extra.eas.build.experimental ??= {};
  const experimental = config.extra.eas.build.experimental;
  const extensions = experimental.ios?.appExtensions ?? [];
  experimental.ios = {
    ...experimental.ios,
    appExtensions: [
      ...extensions.filter((extension) => extension.targetName !== targetName),
      {
        targetName,
        bundleIdentifier: `${bundleId}.ShareExtension`,
        entitlements: { "com.apple.security.application-groups": [appGroup] },
      },
    ],
  };
  return withXcodeProject(config, (mod) => {
    configureProject(mod.modResults, mod.modRequest.platformProjectRoot, config);
    return mod;
  });
}
module.exports = withBotSharing;
module.exports.configureProject = configureProject;
